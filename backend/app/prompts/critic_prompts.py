"""
critic_prompts.py

Prompt definitions for the Clinical Decision Support Critic Agent.

Purpose:
    Perform final quality-control analysis of the outputs produced by
    the upstream clinical agents.

Workflow:

    Intake
       |
    Context
       |
    Evidence / RAG
       |
    Differential
       |
    Missing Information
       |
    Diagnostic Tests
       |
    Safety
       |
    Critic Agent
       |
       +----> Re-analysis
       |
       +----> Summary

The Critic Agent is responsible for identifying:

    - Unsupported clinical claims
    - Hallucinated facts
    - Fabricated evidence
    - Fabricated citations
    - Evidence grounding problems
    - Contradictions
    - Missing diagnostic possibilities
    - Diagnostic reasoning gaps
    - Missing clinical information
    - Safety gaps
    - Inappropriate test suggestions
    - Overconfident conclusions
    - Failure to preserve uncertainty

The Critic Agent must NOT:

    - Make a final diagnosis.
    - Prescribe treatment.
    - Order tests.
    - Invent clinical information.
    - Replace the clinician.
    - Convert LLM confidence into clinical probability.

All final clinical outputs require clinician review.

```

### Where this fits in your agentic loop

Your Critic prompt is deliberately different from the Diagnosis prompt:

```text
                    Clinical State
                         │
                         ▼
                ┌─────────────────┐
                │  Critic Agent   │
                └────────┬────────┘
                         │
          ┌──────────────┼──────────────┐
          │              │              │
          ▼              ▼              ▼
       Grounding    Contradictions    Safety
          │              │              │
          └──────────────┼──────────────┘
                         ▼
                   CriticResult
                         │
                  ┌──────┴──────┐
                  │             │
                PASS          FAIL
                  │             │
                  ▼             ▼
               Summary      Re-analysis
                                │
              ┌─────────────────┼────────────────┐
              ▼                 ▼                ▼
           Evidence        Differential       Safety
              │                 │                │
              └─────────────────┴────────────────┘
                                │
                                ▼
                              Critic
                                │
                                ▼
                             Summary
                                │
                                ▼
                         Human Review
```

### Key design principle

The Critic is **not another diagnosis agent**.

Its role is:

> **Challenge the reasoning produced by the other agents and identify whether it is sufficiently grounded, consistent, complete, and safe for clinician review.**

That gives your overall Agentic AI workflow a strong pattern:

**Extract → Contextualize → Retrieve → Reason → Identify Gaps → Suggest → Check Safety → Critique → Re-analyze → Summarize → Human Review**

The `CRITIC_PROMPT_VERSION` also gives you a foundation for prompt evaluation and LLMOps: you can associate every Critic execution with a specific prompt version and later compare hallucination, re-analysis, grounding, and safety metrics across prompt versions.

"""

