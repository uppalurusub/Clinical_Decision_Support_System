# ============================================================================
# Prompt Builder
# ============================================================================


class CriticPromptBuilder:
    """
    Builds the prompt used by CriticAgent.

    Responsibilities:
        - Maintain prompt version.
        - Construct system/human prompts.
        - Map ClinicalState into prompt variables.
        - Provide prompt metadata.

    This class contains no clinical reasoning.
    """

    def __init__(
        self,
        *,
        version: str = CRITIC_PROMPT_VERSION,
    ) -> None:
        """
        Initialize CriticPromptBuilder.
        """

        self.version = version

        logger.debug(
            "CriticPromptBuilder initialized | version={}",
            self.version,
        )

    # =========================================================================
    # System Prompt
    # =========================================================================

    def get_system_prompt(self) -> str:
        """
        Return the Critic Agent system prompt.
        """

        logger.debug(
            "Critic system prompt requested | version={}",
            self.version,
        )

        return CRITIC_SYSTEM_PROMPT.strip()

    # =========================================================================
    # Human Prompt
    # =========================================================================

    def get_human_prompt(self) -> str:
        """
        Return the Critic Agent human prompt template.
        """

        logger.debug(
            "Critic human prompt requested | version={}",
            self.version,
        )

        return CRITIC_HUMAN_PROMPT.strip()

    # =========================================================================
    # Chat Prompt
    # =========================================================================

    def build(self) -> ChatPromptTemplate:
        """
        Build the LangChain ChatPromptTemplate.
        """

        logger.info(
            "Building Critic Agent prompt | version={}",
            self.version,
        )

        prompt = ChatPromptTemplate.from_messages(
            [
                (
                    "system",
                    self.get_system_prompt(),
                ),
                (
                    "human",
                    self.get_human_prompt(),
                ),
            ]
        )

        logger.info(
            "Critic Agent prompt built successfully | version={}",
            self.version,
        )

        return prompt

    # =========================================================================
    # Input Variables
    # =========================================================================

    @staticmethod
    def get_input_variables() -> List[str]:
        """
        Return all variables expected by the Critic prompt.
        """

        variables = [
            "intake_result",
            "clinical_context",
            "active_problems",
            "risk_factors",
            "abnormal_findings",
            "temporal_events",
            "unresolved_issues",
            "evidence",
            "evidence_gaps",
            "differential_diagnosis",
            "diagnostic_reasoning",
            "diagnostic_uncertainties",
            "missing_information",
            "critical_information_gaps",
            "clinical_contradictions",
            "suggested_tests",
            "test_assessment",
            "safety_flags",
            "safety_assessment",
            "data_quality_concerns",
            "medication_safety_concerns",
            "diagnostic_safety_concerns",
        ]

        logger.debug(
            "Critic prompt variables requested | count={}",
            len(variables),
        )

        return variables

    # =========================================================================
    # Prompt Values
    # =========================================================================

    def format_prompt_values(
        self,
        *,
        intake_result: Dict[str, Any],
        clinical_context: Dict[str, Any],
        active_problems: List[Dict[str, Any]],
        risk_factors: List[Dict[str, Any]],
        abnormal_findings: List[Dict[str, Any]],
        temporal_events: List[Dict[str, Any]],
        unresolved_issues: List[str],
        evidence: List[Dict[str, Any]],
        evidence_gaps: List[str],
        differential_diagnosis: List[Dict[str, Any]],
        diagnostic_reasoning: str,
        diagnostic_uncertainties: List[str],
        missing_information: List[Dict[str, Any]],
        critical_information_gaps: List[str],
        clinical_contradictions: List[str],
        suggested_tests: List[Dict[str, Any]],
        test_assessment: str,
        safety_flags: List[Dict[str, Any]],
        safety_assessment: str,
        data_quality_concerns: List[str],
        medication_safety_concerns: List[str],
        diagnostic_safety_concerns: List[str],
    ) -> Dict[str, Any]:
        """
        Map ClinicalState data to Critic prompt variables.

        This method performs no clinical reasoning.
        """

        logger.debug(
            "Formatting Critic prompt values | "
            "evidence_count={} | differential_count={} | "
            "missing_info_count={} | test_count={} | "
            "safety_flag_count={} | contradiction_count={}",
            len(evidence),
            len(differential_diagnosis),
            len(missing_information),
            len(suggested_tests),
            len(safety_flags),
            len(clinical_contradictions),
        )

        return {
            "intake_result": intake_result,
            "clinical_context": clinical_context,
            "active_problems": active_problems,
            "risk_factors": risk_factors,
            "abnormal_findings": abnormal_findings,
            "temporal_events": temporal_events,
            "unresolved_issues": unresolved_issues,
            "evidence": evidence,
            "evidence_gaps": evidence_gaps,
            "differential_diagnosis": differential_diagnosis,
            "diagnostic_reasoning": diagnostic_reasoning,
            "diagnostic_uncertainties": diagnostic_uncertainties,
            "missing_information": missing_information,
            "critical_information_gaps": critical_information_gaps,
            "clinical_contradictions": clinical_contradictions,
            "suggested_tests": suggested_tests,
            "test_assessment": test_assessment,
            "safety_flags": safety_flags,
            "safety_assessment": safety_assessment,
            "data_quality_concerns": data_quality_concerns,
            "medication_safety_concerns": medication_safety_concerns,
            "diagnostic_safety_concerns": diagnostic_safety_concerns,
        }

    # =========================================================================
    # Metadata
    # =========================================================================

    def get_metadata(self) -> Dict[str, Any]:
        """
        Return metadata for prompt observability and evaluation.
        """

        metadata = {
            "prompt_name": "clinical_decision_critic",
            "prompt_version": self.version,
            "agent": "CriticAgent",
            "purpose": "clinical_workflow_quality_control",
            "clinician_review_required": True,
            "supports_reanalysis_routing": True,
        }

        logger.debug(
            "Critic prompt metadata requested | version={}",
            self.version,
        )

        return metadata


# ============================================================================
# Convenience Function
# ============================================================================


def create_critic_prompt(
    *,
    version: str = CRITIC_PROMPT_VERSION,
) -> ChatPromptTemplate:
    """
    Create the Critic Agent prompt.

    Example:

        prompt = create_critic_prompt()

        structured_llm = llm.with_structured_output(
            CriticResult
        )

        chain = prompt | structured_llm
    """

    logger.debug(
        "Creating Critic Agent prompt | version={}",
        version,
    )

    builder = CriticPromptBuilder(
        version=version,
    )

    return builder.build()