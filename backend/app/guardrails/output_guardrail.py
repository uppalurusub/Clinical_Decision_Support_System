"""
app/guardrails/output_guardrail.py

Output Guardrail for the Clinical Decision Support system.

Purpose:
    Validate the output generated by the clinical Agentic AI workflow
    before it is returned to the API consumer.

Architecture:

    ClinicalGraph
         |
         v
    SummaryAgent
         |
         v
    OutputGuardrail
         |
         +--------------------+
         |                    |
       ALLOW                BLOCK/REVIEW
         |                    |
         v                    v
     API Response        Safe Error / Review

Responsibilities:
    - Validate required output fields
    - Detect missing safety information
    - Verify clinician-review requirement
    - Detect unsupported definitive diagnosis language
    - Detect treatment/prescription language
    - Detect fabricated-looking citations
    - Detect incomplete safety information
    - Validate output size
    - Preserve uncertainty
    - Prevent unsafe output from being returned directly

Non-responsibilities:
    - Does NOT independently diagnose
    - Does NOT determine whether a diagnosis is clinically correct
    - Does NOT replace physician review
    - Does NOT perform clinical reasoning
    - Does NOT rewrite clinical recommendations silently

Security:
    - Never log clinical summary
    - Never log diagnosis text
    - Never log medications
    - Never log laboratory values
    - Never log patient data
    - Never log complete LLM responses
    - Log only safe metadata and rule identifiers
"""

from __future__ import annotations

import re
from enum import Enum
from typing import Any, Dict, List, Optional

from app.config.settings import settings
logger = settings.get_logger()

from pydantic import BaseModel, Field


# =============================================================================
# Configuration
# =============================================================================

MAX_SUMMARY_LENGTH = 20_000
MAX_LIMITATIONS = 50
MAX_NEXT_STEPS = 50
MAX_SAFETY_ALERTS = 50


# =============================================================================
# Enumerations
# =============================================================================


class OutputGuardrailSeverity(str, Enum):
    """
    Severity of an output guardrail finding.
    """

    INFO = "info"
    WARNING = "warning"
    HIGH = "high"
    CRITICAL = "critical"


class OutputGuardrailAction(str, Enum):
    """
    Action to take after output validation.
    """

    ALLOW = "allow"
    REVIEW = "review"
    BLOCK = "block"


# =============================================================================
# Pydantic Models
# =============================================================================


class OutputGuardrailFinding(BaseModel):
    """
    Individual output guardrail finding.

    The finding intentionally contains rule identifiers and safe
    metadata rather than reproducing clinical output.
    """

    rule_id: str = Field(
        ...,
        description="Output guardrail rule identifier.",
    )

    field: Optional[str] = Field(
        default=None,
        description="Output field associated with the finding.",
    )

    severity: OutputGuardrailSeverity = Field(
        ...,
        description="Severity of the finding.",
    )

    action: OutputGuardrailAction = Field(
        ...,
        description="Action associated with the finding.",
    )

    reason: str = Field(
        ...,
        description="Safe explanation of the finding.",
    )


class OutputGuardrailResult(BaseModel):
    """
    Result of output validation.
    """

    allowed: bool = Field(
        ...,
        description="Whether output may be returned.",
    )

    action: OutputGuardrailAction = Field(
        ...,
        description="Overall output guardrail action.",
    )

    findings: List[OutputGuardrailFinding] = Field(
        default_factory=list,
        description="Detected output issues.",
    )

    requires_human_review: bool = Field(
        default=True,
        description="Whether human review is required.",
    )

    sanitized_output: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Output after safe non-clinical normalization.",
    )

    rule_count: int = Field(
        default=0,
        description="Number of rules that produced findings.",
    )


# =============================================================================
# Output Guardrail
# =============================================================================


class OutputGuardrail:
    """
    Output guardrail for the Clinical Decision Support workflow.

    The guardrail operates after the Summary Agent and before the
    response is returned to the client.

    It checks structural and safety properties of the generated output.

    IMPORTANT:

        Passing this guardrail does NOT mean the clinical output is
        clinically correct.

        It means the output passed the configured technical and
        safety-oriented validation checks.
    """

    def __init__(
        self,
        max_summary_length: int = MAX_SUMMARY_LENGTH,
        max_limitations: int = MAX_LIMITATIONS,
        max_next_steps: int = MAX_NEXT_STEPS,
        max_safety_alerts: int = MAX_SAFETY_ALERTS,
    ) -> None:

        self.max_summary_length = max_summary_length
        self.max_limitations = max_limitations
        self.max_next_steps = max_next_steps
        self.max_safety_alerts = max_safety_alerts

        logger.info(
            "OutputGuardrail initialized | max_summary_length={} | "
            "max_limitations={} | max_next_steps={} | "
            "max_safety_alerts={}",
            max_summary_length,
            max_limitations,
            max_next_steps,
            max_safety_alerts,
        )

    # =========================================================================
    # Public API
    # =========================================================================

    async def validate(
        self,
        output: Any,
        workflow_id: Optional[str] = None,
    ) -> OutputGuardrailResult:
        """
        Validate the clinical workflow output.

        Args:
            output:
                Final ClinicalState or response model.

            workflow_id:
                Safe workflow correlation ID.

        Returns:
            OutputGuardrailResult.
        """

        logger.info(
            "OutputGuardrail validation started | workflow_id={}",
            workflow_id or "unknown",
        )

        try:

            data = self._to_dict(output)

            findings: List[OutputGuardrailFinding] = []

            # -------------------------------------------------------------
            # Structural validation
            # -------------------------------------------------------------

            findings.extend(
                self._validate_required_fields(data)
            )

            findings.extend(
                self._validate_field_types(data)
            )

            # -------------------------------------------------------------
            # Size validation
            # -------------------------------------------------------------

            findings.extend(
                self._validate_output_sizes(data)
            )

            # -------------------------------------------------------------
            # Human review validation
            # -------------------------------------------------------------

            findings.extend(
                self._validate_human_review(data)
            )

            # -------------------------------------------------------------
            # Clinical safety validation
            # -------------------------------------------------------------

            findings.extend(
                self._validate_safety_information(data)
            )

            # -------------------------------------------------------------
            # Uncertainty validation
            # -------------------------------------------------------------

            findings.extend(
                self._validate_uncertainty(data)
            )

            # -------------------------------------------------------------
            # Definitive diagnosis detection
            # -------------------------------------------------------------

            findings.extend(
                self._detect_definitive_diagnosis_language(data)
            )

            # -------------------------------------------------------------
            # Treatment/prescription detection
            # -------------------------------------------------------------

            findings.extend(
                self._detect_treatment_language(data)
            )

            # -------------------------------------------------------------
            # Unsupported certainty detection
            # -------------------------------------------------------------

            findings.extend(
                self._detect_overconfidence(data)
            )

            # -------------------------------------------------------------
            # Citation validation
            # -------------------------------------------------------------

            findings.extend(
                self._validate_citations(data)
            )

            # -------------------------------------------------------------
            # Critic validation
            # -------------------------------------------------------------

            findings.extend(
                self._validate_critic_status(data)
            )

            # -------------------------------------------------------------
            # Determine action
            # -------------------------------------------------------------

            action = self._determine_action(findings)

            allowed = action != OutputGuardrailAction.BLOCK

            # Clinical outputs always require clinician review.
            requires_human_review = True

            sanitized_output = None

            if allowed:

                sanitized_output = (
                    self._sanitize_output(data)
                )

            result = OutputGuardrailResult(
                allowed=allowed,
                action=action,
                findings=findings,
                requires_human_review=requires_human_review,
                sanitized_output=sanitized_output,
                rule_count=len(findings),
            )

            logger.info(
                "OutputGuardrail validation completed | "
                "workflow_id={} | allowed={} | action={} | "
                "findings={} | human_review=true",
                workflow_id or "unknown",
                allowed,
                action.value,
                len(findings),
            )

            return result

        except Exception:

            logger.exception(
                "OutputGuardrail validation failed | workflow_id={}",
                workflow_id or "unknown",
            )

            raise

    # =========================================================================
    # Required Fields
    # =========================================================================

    def _validate_required_fields(
        self,
        data: Dict[str, Any],
    ) -> List[OutputGuardrailFinding]:
        """
        Validate required final-output fields.
        """

        findings = []

        required_fields = [
            "clinical_summary",
            "differential_summary",
            "safety_alerts",
            "limitations",
        ]

        for field_name in required_fields:

            if field_name not in data:

                findings.append(
                    OutputGuardrailFinding(
                        rule_id="OUTPUT-001",
                        field=field_name,
                        severity=OutputGuardrailSeverity.CRITICAL,
                        action=OutputGuardrailAction.BLOCK,
                        reason=(
                            "Required clinical output field is missing."
                        ),
                    )
                )

        return findings

    # =========================================================================
    # Field Types
    # =========================================================================

    def _validate_field_types(
        self,
        data: Dict[str, Any],
    ) -> List[OutputGuardrailFinding]:
        """
        Validate expected output types.
        """

        findings = []

        string_fields = [
            "clinical_summary",
            "final_summary",
            "human_review_reason",
        ]

        list_fields = [
            "key_findings",
            "differential_summary",
            "summary_information_gaps",
            "suggested_next_steps",
            "safety_alerts",
            "evidence_citations",
            "limitations",
        ]

        for field_name in string_fields:

            if field_name not in data:
                continue

            value = data.get(field_name)

            if value is not None and not isinstance(value, str):

                findings.append(
                    OutputGuardrailFinding(
                        rule_id="OUTPUT-002",
                        field=field_name,
                        severity=OutputGuardrailSeverity.CRITICAL,
                        action=OutputGuardrailAction.BLOCK,
                        reason="Output field must be a string.",
                    )
                )

        for field_name in list_fields:

            if field_name not in data:
                continue

            value = data.get(field_name)

            if value is not None and not isinstance(
                value,
                list,
            ):

                findings.append(
                    OutputGuardrailFinding(
                        rule_id="OUTPUT-003",
                        field=field_name,
                        severity=OutputGuardrailSeverity.CRITICAL,
                        action=OutputGuardrailAction.BLOCK,
                        reason="Output field must be a list.",
                    )
                )

        return findings

    # =========================================================================
    # Output Size
    # =========================================================================

    def _validate_output_sizes(
        self,
        data: Dict[str, Any],
    ) -> List[OutputGuardrailFinding]:
        """
        Validate output size limits.
        """

        findings = []

        summary = data.get(
            "clinical_summary",
            data.get("final_summary"),
        )

        if isinstance(summary, str):

            if len(summary) > self.max_summary_length:

                findings.append(
                    OutputGuardrailFinding(
                        rule_id="OUTPUT-004",
                        field="clinical_summary",
                        severity=OutputGuardrailSeverity.HIGH,
                        action=OutputGuardrailAction.REVIEW,
                        reason=(
                            "Clinical summary exceeds configured "
                            "maximum output length."
                        ),
                    )
                )

        list_limits = {
            "limitations": self.max_limitations,
            "suggested_next_steps": self.max_next_steps,
            "safety_alerts": self.max_safety_alerts,
        }

        for field_name, maximum in list_limits.items():

            value = data.get(field_name)

            if isinstance(value, list) and len(value) > maximum:

                findings.append(
                    OutputGuardrailFinding(
                        rule_id="OUTPUT-005",
                        field=field_name,
                        severity=OutputGuardrailSeverity.HIGH,
                        action=OutputGuardrailAction.REVIEW,
                        reason=(
                            "Output contains more items than the "
                            "configured maximum."
                        ),
                    )
                )

        return findings

    # =========================================================================
    # Human Review
    # =========================================================================

    def _validate_human_review(
        self,
        data: Dict[str, Any],
    ) -> List[OutputGuardrailFinding]:
        """
        Ensure clinical output cannot bypass human review.
        """

        findings = []

        requires_review = data.get(
            "requires_human_review"
        )

        if requires_review is not True:

            findings.append(
                OutputGuardrailFinding(
                    rule_id="SAFETY-OUTPUT-001",
                    field="requires_human_review",
                    severity=OutputGuardrailSeverity.CRITICAL,
                    action=OutputGuardrailAction.BLOCK,
                    reason=(
                        "Clinical output must require clinician review."
                    ),
                )
            )

        reason = data.get(
            "human_review_reason"
        )

        if not reason:

            findings.append(
                OutputGuardrailFinding(
                    rule_id="SAFETY-OUTPUT-002",
                    field="human_review_reason",
                    severity=OutputGuardrailSeverity.HIGH,
                    action=OutputGuardrailAction.REVIEW,
                    reason=(
                        "Human review is required but no review "
                        "reason was provided."
                    ),
                )
            )

        return findings

    # =========================================================================
    # Safety Validation
    # =========================================================================

    def _validate_safety_information(
        self,
        data: Dict[str, Any],
    ) -> List[OutputGuardrailFinding]:
        """
        Validate that safety information is preserved.
        """

        findings = []

        safety_alerts = data.get(
            "safety_alerts"
        )

        if safety_alerts is None:

            findings.append(
                OutputGuardrailFinding(
                    rule_id="SAFETY-OUTPUT-003",
                    field="safety_alerts",
                    severity=OutputGuardrailSeverity.CRITICAL,
                    action=OutputGuardrailAction.BLOCK,
                    reason=(
                        "Safety alert information is unavailable."
                    ),
                )
            )

            return findings

        immediate_attention = data.get(
            "immediate_attention_required"
        )

        if immediate_attention is True and not safety_alerts:

            findings.append(
                OutputGuardrailFinding(
                    rule_id="SAFETY-OUTPUT-004",
                    field="safety_alerts",
                    severity=OutputGuardrailSeverity.CRITICAL,
                    action=OutputGuardrailAction.BLOCK,
                    reason=(
                        "Upstream workflow indicates immediate attention "
                        "may be required, but the final output contains "
                        "no safety alerts."
                    ),
                )
            )

        return findings

    # =========================================================================
    # Uncertainty Validation
    # =========================================================================

    def _validate_uncertainty(
        self,
        data: Dict[str, Any],
    ) -> List[OutputGuardrailFinding]:
        """
        Verify that limitations/uncertainty are preserved.
        """

        findings = []

        differential = data.get(
            "differential_summary"
        )

        limitations = data.get(
            "limitations"
        )

        information_gaps = data.get(
            "summary_information_gaps"
        )

        if differential and not limitations and not information_gaps:

            findings.append(
                OutputGuardrailFinding(
                    rule_id="OUTPUT-006",
                    field="limitations",
                    severity=OutputGuardrailSeverity.WARNING,
                    action=OutputGuardrailAction.REVIEW,
                    reason=(
                        "A differential is present but the output does "
                        "not explicitly preserve uncertainty or limitations."
                    ),
                )
            )

        return findings

    # =========================================================================
    # Definitive Diagnosis Detection
    # =========================================================================

    def _detect_definitive_diagnosis_language(
        self,
        data: Dict[str, Any],
    ) -> List[OutputGuardrailFinding]:
        """
        Detect language that may incorrectly present a definitive
        diagnosis.

        This is a lexical safety check, not a clinical correctness check.
        """

        findings = []

        patterns = [
            r"\bdefinitively\s+diagnosed\b",
            r"\bconfirmed\s+diagnosis\s+is\b",
            r"\bthe\s+patient\s+has\s+\w+",
            r"\bdiagnosis\s+is\s+definitively\b",
            r"\bwithout\s+doubt\b",
            r"\bcertainly\s+has\b",
            r"\bdefinitely\s+has\b",
        ]

        clinical_text = self._extract_clinical_text(
            data
        )

        for pattern in patterns:

            if re.search(
                pattern,
                clinical_text,
                flags=re.IGNORECASE,
            ):

                findings.append(
                    OutputGuardrailFinding(
                        rule_id="SAFETY-OUTPUT-005",
                        field="clinical_summary",
                        severity=OutputGuardrailSeverity.HIGH,
                        action=OutputGuardrailAction.REVIEW,
                        reason=(
                            "Output contains language that may present "
                            "a definitive diagnosis without sufficient "
                            "clinical qualification."
                        ),
                    )
                )

                break

        return findings

    # =========================================================================
    # Treatment Detection
    # =========================================================================

    def _detect_treatment_language(
        self,
        data: Dict[str, Any],
    ) -> List[OutputGuardrailFinding]:
        """
        Detect potentially prescriptive treatment language.

        The Summary Agent should summarize clinician-reviewable
        next steps rather than independently prescribe treatment.
        """

        findings = []

        treatment_patterns = [
            r"\bprescribe\b",
            r"\bstart\s+\w+\s+\d+\s*(mg|mcg|g|ml)\b",
            r"\bstop\s+\w+\s+immediately\b",
            r"\bincrease\s+the\s+dose\b",
            r"\bdecrease\s+the\s+dose\b",
            r"\btake\s+\w+\s+\d+\s*(mg|mcg|g|ml)\b",
            r"\brecommended\s+medication\s+is\b",
            r"\bpatient\s+should\s+take\b",
        ]

        clinical_text = self._extract_clinical_text(
            data
        )

        for pattern in treatment_patterns:

            if re.search(
                pattern,
                clinical_text,
                flags=re.IGNORECASE,
            ):

                findings.append(
                    OutputGuardrailFinding(
                        rule_id="SAFETY-OUTPUT-006",
                        field="suggested_next_steps",
                        severity=OutputGuardrailSeverity.HIGH,
                        action=OutputGuardrailAction.REVIEW,
                        reason=(
                            "Output may contain prescriptive treatment "
                            "language and requires clinician review."
                        ),
                    )
                )

                break

        return findings

    # =========================================================================
    # Overconfidence Detection
    # =========================================================================

    def _detect_overconfidence(
        self,
        data: Dict[str, Any],
    ) -> List[OutputGuardrailFinding]:
        """
        Detect excessive certainty in generated output.
        """

        findings = []

        patterns = [
            r"\b100%\s+certain\b",
            r"\b100\s*percent\s+certain\b",
            r"\bno\s+doubt\b",
            r"\bwithout\s+any\s+doubt\b",
            r"\bguaranteed\b",
            r"\bdefinitely\b",
            r"\bcertainly\b",
            r"\babsolute\s+certainty\b",
        ]

        clinical_text = self._extract_clinical_text(
            data
        )

        for pattern in patterns:

            if re.search(
                pattern,
                clinical_text,
                flags=re.IGNORECASE,
            ):

                findings.append(
                    OutputGuardrailFinding(
                        rule_id="OUTPUT-007",
                        field="clinical_summary",
                        severity=OutputGuardrailSeverity.HIGH,
                        action=OutputGuardrailAction.REVIEW,
                        reason=(
                            "Output contains potentially excessive "
                            "clinical certainty."
                        ),
                    )
                )

                break

        return findings

    # =========================================================================
    # Citation Validation
    # =========================================================================

    def _validate_citations(
        self,
        data: Dict[str, Any],
    ) -> List[OutputGuardrailFinding]:
        """
        Validate the structure of evidence citations.

        This does NOT verify the external source itself.

        Citation verification should be implemented separately using
        the evidence/RAG layer.
        """

        findings = []

        citations = data.get(
            "evidence_citations"
        )

        if citations is None:
            return findings

        if not isinstance(citations, list):
            return findings

        for index, citation in enumerate(citations):

            if not isinstance(citation, dict):

                findings.append(
                    OutputGuardrailFinding(
                        rule_id="EVIDENCE-OUTPUT-001",
                        field=f"evidence_citations[{index}]",
                        severity=OutputGuardrailSeverity.HIGH,
                        action=OutputGuardrailAction.BLOCK,
                        reason=(
                            "Evidence citation has an invalid structure."
                        ),
                    )
                )

                continue

            citation_value = citation.get(
                "citation"
            )

            if not citation_value:

                findings.append(
                    OutputGuardrailFinding(
                        rule_id="EVIDENCE-OUTPUT-002",
                        field=f"evidence_citations[{index}]",
                        severity=OutputGuardrailSeverity.HIGH,
                        action=OutputGuardrailAction.REVIEW,
                        reason=(
                            "Evidence citation is missing its source "
                            "identifier."
                        ),
                    )
                )

        return findings

    # =========================================================================
    # Critic Validation
    # =========================================================================

    def _validate_critic_status(
        self,
        data: Dict[str, Any],
    ) -> List[OutputGuardrailFinding]:
        """
        Validate that critic findings have not been silently ignored.
        """

        findings = []

        hallucination_detected = data.get(
            "hallucination_detected"
        )

        critic_passed = data.get(
            "critic_passed"
        )

        if hallucination_detected is True:

            findings.append(
                OutputGuardrailFinding(
                    rule_id="CRITIC-OUTPUT-001",
                    field="hallucination_detected",
                    severity=OutputGuardrailSeverity.CRITICAL,
                    action=OutputGuardrailAction.BLOCK,
                    reason=(
                        "The Critic Agent detected potential hallucinated "
                        "content. The output must not be released without "
                        "re-analysis or clinician review."
                    ),
                )
            )

        if critic_passed is False:

            findings.append(
                OutputGuardrailFinding(
                    rule_id="CRITIC-OUTPUT-002",
                    field="critic_passed",
                    severity=OutputGuardrailSeverity.HIGH,
                    action=OutputGuardrailAction.REVIEW,
                    reason=(
                        "The Critic Agent did not pass the generated "
                        "clinical synthesis."
                    ),
                )
            )

        return findings

    # =========================================================================
    # Action Resolution
    # =========================================================================

    def _determine_action(
        self,
        findings: List[OutputGuardrailFinding],
    ) -> OutputGuardrailAction:
        """
        Determine the overall output action.

        Priority:

            BLOCK > REVIEW > ALLOW
        """

        if any(
            finding.action == OutputGuardrailAction.BLOCK
            for finding in findings
        ):
            return OutputGuardrailAction.BLOCK

        if any(
            finding.action == OutputGuardrailAction.REVIEW
            for finding in findings
        ):
            return OutputGuardrailAction.REVIEW

        return OutputGuardrailAction.ALLOW

    # =========================================================================
    # Safe Normalization
    # =========================================================================

    def _sanitize_output(
        self,
        data: Dict[str, Any],
    ) -> Dict[str, Any]:
        """
        Perform only safe structural normalization.

        IMPORTANT:

        This method intentionally does not rewrite clinical meaning.

        Clinical content should not be silently changed by a generic
        output sanitizer.
        """

        sanitized = dict(data)

        if isinstance(
            sanitized.get("clinical_summary"),
            str,
        ):
            sanitized["clinical_summary"] = (
                sanitized["clinical_summary"].strip()
            )

        if isinstance(
            sanitized.get("final_summary"),
            str,
        ):
            sanitized["final_summary"] = (
                sanitized["final_summary"].strip()
            )

        # Always enforce clinician review.
        sanitized["requires_human_review"] = True

        if not sanitized.get("human_review_reason"):
            sanitized["human_review_reason"] = (
                "Clinical AI output requires clinician review."
            )

        return sanitized

    # =========================================================================
    # Utility Methods
    # =========================================================================

    @staticmethod
    def _to_dict(
        output: Any,
    ) -> Dict[str, Any]:
        """
        Convert Pydantic model, dict, or object into a dictionary.
        """

        if isinstance(output, dict):
            return dict(output)

        if hasattr(output, "model_dump"):
            return output.model_dump()

        if hasattr(output, "dict"):
            return output.dict()

        raise TypeError(
            "Output must be a dictionary or Pydantic model."
        )

    @staticmethod
    def _extract_clinical_text(
        data: Dict[str, Any],
    ) -> str:
        """
        Extract textual output for lexical safety checks.

        This content is never logged.
        """

        values: List[str] = []

        text_fields = [
            "clinical_summary",
            "final_summary",
            "human_review_reason",
            "limitations",
            "suggested_next_steps",
            "differential_summary",
            "summary_information_gaps",
            "safety_alerts",
        ]

        for field_name in text_fields:

            value = data.get(field_name)

            if value is None:
                continue

            if isinstance(value, str):
                values.append(value)

            elif isinstance(value, list):

                for item in value:

                    if isinstance(item, str):
                        values.append(item)

                    elif isinstance(item, dict):

                        values.extend(
                            str(v)
                            for v in item.values()
                            if v is not None
                        )

                    else:
                        values.append(str(item))

            elif isinstance(value, dict):

                values.extend(
                    str(v)
                    for v in value.values()
                    if v is not None
                )

        return " ".join(values)